/* ── Format + domain-separation tags ───────────────────────────────────── */

/** Format id of the container. Also the CLI's auto-detect discriminant. */
export const COUNTERSIGN_BUNDLE_FORMAT = "kashscript-countersign/1" as const;

/** DST of the holder's request. Registered in `./dst`. */
export const DST_COUNTERSIGN_REQUEST = "kash-countersign-request-v1\n" as const;
/** DST of the counterparty's acceptance. */
export const DST_COUNTERSIGN_ACCEPTANCE = "kash-countersign-v1\n" as const;
/** DST of the holder's withdrawal. */
export const DST_COUNTERSIGN_WITHDRAWAL = "kash-countersign-withdrawal-v1\n" as const;

/**
 * Where the signing key came from — carried INSIDE the signed acceptance so a
 * verifier reads it without asking anyone.
 *
 *   • `subject-generated` — minted on the signer's own device and never
 *     transmitted. Decision 27 rule 1 holds.
 *   • `delegated-mint` — minted by a server, relay or operator and conveyed to
 *     the signer (the `issueGuestDid` path, and the only path open to a
 *     counterparty whose phone cannot hold a key). Whoever minted it may still
 *     hold a copy, so a record signed under one is **not subject-held**. Saying
 *     otherwise would be exactly the unqualified claim decision 11 forbids.
 */
export type KeyCustody = "subject-generated" | "delegated-mint";

/** What a verifier reports: the two words a signer may write, or `unknown` for an acceptance that states none, or anything else (AU-3, A7-05). Only `subject-generated` is subject-held. */
export type ReportedKeyCustody = KeyCustody | "unknown";

/* ── The signed shapes ─────────────────────────────────────────────────── */

/** One line the counterparty reads before deciding. Nothing else is disclosed. */
export interface CountersignDisclosure {
  readonly label: string;
  readonly value: string;
}

/**
 * The holder's request.
 *
 * It names **no counterparty**: possession of the link is the address. A
 * durable recipient identifier here would be a correlation key across every
 * book in the ecosystem, which decision 41's *separate identifiers per
 * relationship* exists to prevent.
 */
export interface CountersignRequestBody {
  /** `csr_<32hex>` — SHA-256 of the capability secret, truncated. Holding the id
   *  does not let you sign; only the secret opens the request. */
  readonly requestId: string;
  readonly requesterDid: string;
  /** The subject envelope's `payloadType`, bound so a request cannot be moved. */
  readonly subjectPayloadType: string;
  /** SHA-256 over the subject envelope's exact payload bytes. */
  readonly subjectDigestSha256: string;
  /** One plain sentence — what the counterparty is being asked to sign. */
  readonly statement: string;
  readonly disclosures: readonly CountersignDisclosure[];
  /** 32 random bytes, base64. Freshness, and part of the request digest. */
  readonly nonceB64: string;
  readonly issuedAtUnix: number;
  readonly expiresAtUnix: number;
  /** An opaque, requester-scoped label. With `requesterDid` it is the salt a
   *  wallet derives its per-relationship signing key from. Never a person. */
  readonly relationshipContext: string;
  /** Optional: an address THE HOLDER controls where withdrawals may be
   *  published. Never ours, never fetched by any verifier here. */
  readonly withdrawalFeed?: string | null;
}

/** A Kash-Event: `{header, body}` canonicalized, DST-prefixed, Ed25519-signed. */
export interface SignedCountersignRequest {
  readonly header: Readonly<Record<string, unknown>>;
  readonly body: CountersignRequestBody;
  readonly signature: KashEventSignature;
}

/** What the counterparty asserts, alongside the DSSE countersignature itself. */
export interface CountersignAcceptanceBody {
  readonly act: "countersign";
  readonly requestId: string;
  /** SHA-256 over JCS(`{header, body}`) of the signed request. Binds the nonce,
   *  the statement, the disclosures and the window in one value — tamper with
   *  any of them and this stops matching. */
  readonly requestDigestSha256: string;
  readonly subjectPayloadType: string;
  readonly subjectDigestSha256: string;
  readonly countersignerDid: string;
  readonly keyCustody: KeyCustody;
  readonly signedAtUnix: number;
}

export interface SignedCountersignAcceptance {
  readonly header: Readonly<Record<string, unknown>>;
  readonly body: CountersignAcceptanceBody;
  readonly signature: KashEventSignature;
}

/** A holder withdrawing a request. Presented, never looked up. */
export interface CountersignWithdrawalBody {
  readonly act: "withdraw";
  readonly requestId: string;
  readonly requestDigestSha256: string;
  readonly withdrawnAtUnix: number;
}

export interface SignedCountersignWithdrawal {
  readonly header: Readonly<Record<string, unknown>>;
  readonly body: CountersignWithdrawalBody;
  readonly signature: KashEventSignature;
}

/* ── The container ─────────────────────────────────────────────────────── */

/**
 * The artifact a stranger verifies. **Unsigned on purpose** — see the module
 * header. `subject` is an ordinary DSSE envelope carrying two or more
 * signatures over the same bytes.
 */
export interface CountersignBundle {
  readonly formatVersion: typeof COUNTERSIGN_BUNDLE_FORMAT;
  readonly subject: DsseEnvelope;
  readonly request: SignedCountersignRequest;
  readonly acceptances: readonly SignedCountersignAcceptance[];
  readonly withdrawal?: SignedCountersignWithdrawal | null;
  /** Key-succession claims, either path (`./succession`). */
  readonly keyClaims?: readonly KeyClaim[];
}

/* ── Verification ──────────────────────────────────────────────────────── */

export type CountersignFailureReason =
  | "MALFORMED_BUNDLE"
  | "REQUEST_DST_MISMATCH"
  | "REQUEST_SIGNATURE_INVALID"
  | "SUBJECT_TYPE_MISMATCH"
  | "SUBJECT_DIGEST_MISMATCH"
  | "SUBJECT_SIGNATURE_INVALID"
  | "NOT_COUNTERSIGNED"
  | "ACCEPTANCE_DST_MISMATCH"
  | "ACCEPTANCE_SIGNATURE_INVALID"
  | "ACCEPTANCE_BINDING_MISMATCH"
  | "SIGNED_OUTSIDE_WINDOW"
  | "COUNTERSIGNER_NOT_IN_ENVELOPE"
  /** Every acceptance that verifies is the requester's own key — a signature over its own claim, never a countersignature (d26; AU-3, A7-02). */
  | "COUNTERSIGNER_IS_REQUESTER"
  | "WITHDRAWN_BEFORE_SIGNING"
  | "WITHDRAWAL_SIGNATURE_INVALID"
  | "KEY_CLAIM_INVALID"
  /** This runtime cannot run a key's algorithm (older browsers lack Ed25519). Nothing was judged. */
  | "RUNTIME_CANNOT_CHECK";

/** Per-acceptance verdict. Every field is an independent fact, not a summary. */
export interface CountersignAcceptanceReport {
  /** The signer in canonical form — the `did:kash` of the key its `countersignerDid` resolves to. */
  readonly countersignerDid: string;
  readonly signedAtUnix: number;
  /** `subject-generated`, `delegated-mint`, or `unknown` when the acceptance states neither. */
  readonly keyCustody: ReportedKeyCustody;
  /** True only for `subject-generated`. The honest form of "the subject holds the key". */
  readonly subjectHeldKey: boolean;
  /** This key is not the requester's. Only an independent acceptance is a countersignature; the requester's own is a signature over its own claim (d26). */
  readonly independent: boolean;
  /** The acceptance Kash-Event's own signature verified. */
  readonly acceptanceSignatureOk: boolean;
  /** It binds this request (id + digest) and this subject (type + digest). */
  readonly bindingOk: boolean;
  /** `issuedAtUnix <= signedAtUnix <= expiresAtUnix`. */
  readonly inWindow: boolean;
  /** This key's DSSE signature over the subject's PAE bytes verified. */
  readonly countersignedSubject: boolean;
  readonly ok: boolean;
  readonly reason: CountersignFailureReason | null;
}

export interface CountersignVerifyReport {
  readonly ok: boolean;
  readonly formatVersion: string;
  readonly requestId: string | null;
  /** The requester in canonical form. */
  readonly requesterDid: string | null;
  readonly requestSignatureOk: boolean;
  readonly requestDigestSha256: string | null;
  readonly subjectPayloadType: string | null;
  readonly subjectDigestSha256: string | null;
  readonly subjectSignatureOk: boolean;
  /** The distinct keys that signed the subject, each in canonical form — one entry per key, whatever the envelope's spellings. */
  readonly subjectVerifiedKeyids: readonly string[];
  /** Distinct keys that signed the same bytes. `< 2` is not proof (d41). */
  readonly independentSignatureCount: number;
  /** Two or more distinct keys over the bytes, and at least one acceptance that verifies and is not the requester's own. */
  readonly twoSignatureProof: boolean;
  /** The requester's key is among the subject's signers. A fact, not a rule: an organisation may request on its doer's record. */
  readonly requesterSignedSubject: boolean;
  readonly acceptances: readonly CountersignAcceptanceReport[];
  readonly withdrawalPresented: boolean;
  readonly withdrawalSignatureOk: boolean | null;
  readonly withdrawnBeforeSigning: boolean;
  readonly keyClaims: readonly CountersignKeyClaimReport[];
  /** Plain-language facts a reader must not have to infer. Always non-empty. */
  readonly notes: readonly string[];
  readonly reason: CountersignFailureReason | null;
}

/** Offline `did:kash` key resolution, typed — Ed25519 or P-256, as the DID
 *  declares. Null for anything unparseable: a bad keyid makes a signature
 *  unverifiable, never a crash. */
const resolveDidKashKey = resolveDidKey;

/** SHA-256 over JCS(`{header, body}`) — the value an acceptance binds to. */
export async function countersignRequestDigest(
  request: Pick<SignedCountersignRequest, "header" | "body">,
): Promise<string> {
  return sha256Hex(canonicalizeBytes({ header: request.header, body: request.body }));
}

/** Verify one Kash-Event under an expected DST and an expected signer DID.
 *  The DST is asserted, not merely used: a valid signature re-labelled with a
 *  different tag would otherwise sail through (the cross-prefix attack the
 *  Indus token tests already cover). */
async function verifyKashEventAs(
  event: SignedKashEvent,
  expectedDst: string,
  signerDid: string,
): Promise<{ ok: boolean; dstOk: boolean }> {
  const dstOk = event.signature?.dst === expectedDst;
  if (!dstOk) return { ok: false, dstOk: false };
  const key = resolveDidKashKey(signerDid);
  if (key === null) return { ok: false, dstOk: true };
  try {
    // The algorithm comes from the signer's did:kash, never from `signature.alg`.
    return { ok: await verifyEventForKey(event, key), dstOk: true };
  } catch (err) {
    if (isAlgorithmUnsupported(err)) throw err;
    return { ok: false, dstOk: true };
  }
}

function isPlainObject(v: unknown): v is Record<string, unknown> {
  return typeof v === "object" && v !== null && !Array.isArray(v);
}

function malformed(note: string): CountersignVerifyReport {
  return {
    ok: false,
    formatVersion: COUNTERSIGN_BUNDLE_FORMAT,
    requestId: null,
    requesterDid: null,
    requestSignatureOk: false,
    requestDigestSha256: null,
    subjectPayloadType: null,
    subjectDigestSha256: null,
    subjectSignatureOk: false,
    subjectVerifiedKeyids: [],
    independentSignatureCount: 0,
    twoSignatureProof: false,
    requesterSignedSubject: false,
    acceptances: [],
    withdrawalPresented: false,
    withdrawalSignatureOk: null,
    withdrawnBeforeSigning: false,
    keyClaims: [],
    notes: [note],
    reason: "MALFORMED_BUNDLE",
  };
}

/**
 * Verify a countersign bundle end to end, offline.
 *
 * No network, no registry, no key material passed in: every public key comes
 * out of a `did:kash` string already inside the artifact. Any input returns a
 * report — `MALFORMED_BUNDLE` for what cannot be read, a junk sibling
 * signature or a request body no signer could have signed included — so a
 * caller handling untrusted files has one code path (AU-3, A7-04). A runtime
 * that cannot run a key's algorithm returns `RUNTIME_CANNOT_CHECK` — never
 * invalid, and never a throw.
 */
export async function verifyCountersignBundle(
  bundle: CountersignBundle,
): Promise<CountersignVerifyReport> {
  try {
    return await verifyCountersignBundleInner(bundle);
  } catch (err) {
    if (isAlgorithmUnsupported(err)) {
      return {
        ...malformed("this runtime cannot run a signature algorithm this bundle needs (Ed25519 arrived late in some browsers) — nothing was judged; check it in Node 22+ or a current browser"),
        reason: "RUNTIME_CANNOT_CHECK",
      };
    }
    return malformed(`the bundle cannot be read: ${err instanceof Error ? err.message : String(err)}`);
  }
}

async function verifyCountersignBundleInner(
  bundle: CountersignBundle,
): Promise<CountersignVerifyReport> {
  if (!isPlainObject(bundle)) return malformed("bundle is not an object");
  if (bundle.formatVersion !== COUNTERSIGN_BUNDLE_FORMAT) {
    return malformed(`unknown formatVersion: ${JSON.stringify(bundle.formatVersion)}`);
  }
  const { subject, request } = bundle;
  if (
    !isPlainObject(subject) ||
    typeof subject.payloadType !== "string" ||
    typeof subject.payload !== "string" ||
    !Array.isArray(subject.signatures)
  ) {
    return malformed("bundle.subject is not a DSSE envelope");
  }
  if (!isPlainObject(request) || !isPlainObject(request.body)) {
    return malformed("bundle.request is not a signed request");
  }
  const acceptances = Array.isArray(bundle.acceptances) ? bundle.acceptances : [];

  const notes: string[] = [];
  let reason: CountersignFailureReason | null = null;
  const fail = (r: CountersignFailureReason): void => {
    reason ??= r;
  };

  /* -- 1. the subject envelope: who signed these exact bytes? ------------ */
  let payloadBytes: Uint8Array;
  try {
    payloadBytes = base64ToBytes(subject.payload);
  } catch {
    return malformed("bundle.subject.payload is not valid base64");
  }
  const subjectDigest = await sha256Hex(payloadBytes);
  const dsse = await verifyEnvelope(subject, resolveDidKashKey);
  // Signers are counted by the key they resolve to: `did:kash:X` and `did:kash:X#c` are one (AU-3, A7-02).
  const canonical = (keyid: string): string => canonicalSignerOf(keyid) ?? keyid;
  const verifiedKeys = [...new Set(dsse.verifiedKeyids.map(canonical))];
  const subjectSignatureOk = verifiedKeys.length > 0;
  if (!subjectSignatureOk) fail("SUBJECT_SIGNATURE_INVALID");
  if (dsse.payloadJson === undefined) {
    notes.push("the subject's payload is not JSON — this check judged its bytes only; a wallet or a desk reads no record in it");
  }

  /* -- 2. the request: does the holder stand behind it? ------------------ */
  const body = request.body as CountersignRequestBody;
  const requesterDid = typeof body.requesterDid === "string" ? canonical(body.requesterDid) : null;
  const requestCheck = await verifyKashEventAs(
    request as SignedKashEvent,
    DST_COUNTERSIGN_REQUEST,
    body.requesterDid,
  );
  if (!requestCheck.dstOk) fail("REQUEST_DST_MISMATCH");
  else if (!requestCheck.ok) fail("REQUEST_SIGNATURE_INVALID");
  const requesterSignedSubject = requesterDid !== null && verifiedKeys.includes(requesterDid);

  if (body.subjectPayloadType !== subject.payloadType) fail("SUBJECT_TYPE_MISMATCH");
  if (body.subjectDigestSha256 !== subjectDigest) fail("SUBJECT_DIGEST_MISMATCH");

  const requestDigest = await countersignRequestDigest(request);

  /* -- 3. the withdrawal, if one was presented -------------------------- */
  const withdrawal = bundle.withdrawal ?? null;
  let withdrawalSignatureOk: boolean | null = null;
  let withdrawnBeforeSigning = false;
  if (withdrawal !== null && isPlainObject(withdrawal)) {
    const check = await verifyKashEventAs(
      withdrawal as unknown as SignedKashEvent,
      DST_COUNTERSIGN_WITHDRAWAL,
      body.requesterDid,
    );
    const bindsRequest =
      withdrawal.body?.requestId === body.requestId &&
      withdrawal.body?.requestDigestSha256 === requestDigest;
    withdrawalSignatureOk = check.ok && bindsRequest;
    if (!withdrawalSignatureOk) {
      fail("WITHDRAWAL_SIGNATURE_INVALID");
      notes.push("a withdrawal was presented but does not verify against this request");
    }
  }

  /* -- 4. each acceptance ------------------------------------------------ */
  const acceptanceReports: CountersignAcceptanceReport[] = [];
  for (const acceptance of acceptances) {
    if (!isPlainObject(acceptance) || !isPlainObject(acceptance.body)) {
      fail("MALFORMED_BUNDLE");
      continue;
    }
    const ab = acceptance.body as unknown as CountersignAcceptanceBody;
    // Custody is what the acceptance states, read exactly; anything else is unknown (AU-3, A7-05).
    const custody: ReportedKeyCustody = ab.keyCustody === "subject-generated" ? "subject-generated" : ab.keyCustody === "delegated-mint" ? "delegated-mint" : "unknown";
    const signerDid = typeof ab.countersignerDid === "string" ? canonical(ab.countersignerDid) : "";
    const check = await verifyKashEventAs(
      acceptance as unknown as SignedKashEvent,
      DST_COUNTERSIGN_ACCEPTANCE,
      ab.countersignerDid,
    );
    const bindingOk =
      ab.act === "countersign" &&
      ab.requestId === body.requestId &&
      ab.requestDigestSha256 === requestDigest &&
      ab.subjectPayloadType === subject.payloadType &&
      ab.subjectDigestSha256 === subjectDigest;
    const inWindow =
      typeof ab.signedAtUnix === "number" &&
      ab.signedAtUnix >= body.issuedAtUnix &&
      ab.signedAtUnix <= body.expiresAtUnix;
    const countersignedSubject = signerDid !== "" && verifiedKeys.includes(signerDid);
    const independent = signerDid !== "" && signerDid !== requesterDid;

    let entryReason: CountersignFailureReason | null = null;
    if (!check.dstOk) entryReason = "ACCEPTANCE_DST_MISMATCH";
    else if (!check.ok) entryReason = "ACCEPTANCE_SIGNATURE_INVALID";
    else if (!bindingOk) entryReason = "ACCEPTANCE_BINDING_MISMATCH";
    else if (!inWindow) entryReason = "SIGNED_OUTSIDE_WINDOW";
    else if (!countersignedSubject) entryReason = "COUNTERSIGNER_NOT_IN_ENVELOPE";

    // A withdrawal only bites when it predates the signing it is set against.
    // Signing a request nobody showed you had been withdrawn is not a fault of
    // the counterparty — but a verifier holding both must still see the order.
    if (
      entryReason === null &&
      withdrawal !== null &&
      withdrawalSignatureOk === true &&
      typeof withdrawal.body?.withdrawnAtUnix === "number" &&
      withdrawal.body.withdrawnAtUnix < ab.signedAtUnix
    ) {
      entryReason = "WITHDRAWN_BEFORE_SIGNING";
      withdrawnBeforeSigning = true;
    }

    if (entryReason !== null) fail(entryReason);
    acceptanceReports.push({
      countersignerDid: signerDid,
      signedAtUnix: typeof ab.signedAtUnix === "number" ? ab.signedAtUnix : 0,
      keyCustody: custody,
      subjectHeldKey: custody === "subject-generated",
      independent,
      acceptanceSignatureOk: check.ok,
      bindingOk,
      inWindow,
      countersignedSubject,
      ok: entryReason === null,
      reason: entryReason,
    });
  }

  /* -- 4b. the proof: two keys over the bytes, and a countersignature that is not the requester's own -- */
  // A countersignature was made when an independent key's acceptance verifies — its signature, its
  // binding, its window, its key over the bytes. A withdrawal dated before it is a status over that
  // countersignature (reported on the entry, `WITHDRAWN_BEFORE_SIGNING`), not a defect in it.
  const made = (a: CountersignAcceptanceReport): boolean => a.ok || a.reason === "WITHDRAWN_BEFORE_SIGNING";
  const countersignatures = acceptanceReports.filter((a) => a.independent && made(a));
  const twoSignatureProof = verifiedKeys.length >= 2 && countersignatures.length > 0;
  if (acceptanceReports.length === 0) {
    fail("NOT_COUNTERSIGNED");
    notes.push("no acceptance presented — the envelope's second signature, if any, is uncontextualised");
  } else if (countersignatures.length === 0 && acceptanceReports.some(made)) {
    fail("COUNTERSIGNER_IS_REQUESTER");
    notes.push("the only acceptance that verifies is the requester's own key — a signature over its own claim, never a countersignature (d26)");
  } else if (verifiedKeys.length < 2) {
    fail("NOT_COUNTERSIGNED");
  }
  if (countersignatures.length > 0 && acceptanceReports.some((a) => !a.independent && made(a))) {
    notes.push("the requester's own acceptance is among the acceptances — a signature, not a countersignature; the proof rests on the independent one(s)");
  }
  if (requesterDid !== null && !requesterSignedSubject) {
    notes.push(`the requester did not sign the subject — its signers are ${verifiedKeys.join(", ") || "none"}; the request stands on its own signature`);
  }

  /* -- 5. key claims, if any — either path, any algorithm --------------- */
  const keyClaimReports: CountersignKeyClaimReport[] = [];
  const claims = (bundle.keyClaims ?? []).filter((claim): claim is KeyClaim => {
    const ok = isPlainObject(claim) && isPlainObject(claim.body) && isPlainObject(claim.signatures);
    if (!ok) fail("KEY_CLAIM_INVALID");
    return ok;
  });
  if (claims.length > 0) {
    const succession = await verifySuccessionSet(claims);
    keyClaimReports.push(...succession.claims);
    if (succession.claims.some((r) => r.reason === "RUNTIME_CANNOT_CHECK")) fail("RUNTIME_CANNOT_CHECK");
    if (!succession.ok) fail("KEY_CLAIM_INVALID");
    for (const c of succession.conflicts) {
      notes.push(`two successors claimed for ${c.priorDid} — neither is trusted for future authority`);
    }
    for (const r of keyClaimReports) {
      const minted = acceptanceReports.find((a) => a.countersignerDid === canonical(r.priorDid) && !a.subjectHeldKey);
      if (minted !== undefined) {
        notes.push(
          `the key claim from ${r.priorDid} moves future authority away from a ${minted.keyCustody === "unknown" ? "key of unknown custody" : "delegated-mint key"} — whoever minted it could have made this claim too${r.path === "helpers" ? ", and named its helpers" : ""}; that acceptance stays ${minted.keyCustody}`,
        );
      }
    }
  }

  /* -- 6. the notes a reader must not have to infer ---------------------- */
  const delegated = acceptanceReports.filter((a) => a.keyCustody === "delegated-mint");
  if (delegated.length > 0) {
    notes.push(
      `${delegated.length} signature(s) use a delegated-mint key: generated by someone other than the signer, ` +
        "so those records are NOT subject-held. A later key claim moves future authority only.",
    );
  }
  const unstated = acceptanceReports.filter((a) => a.keyCustody === "unknown");
  if (unstated.length > 0) {
    notes.push(`${unstated.length} acceptance(s) state no key custody — unknown, so those records are NOT subject-held until the signer says how its key was made`);
  }
  if (withdrawal === null) {
    notes.push("no withdrawal presented — which is not evidence that none exists (offline check, by design)");
  }
  if (body.withdrawalFeed) {
    notes.push(`withdrawal feed named by the requester (never fetched here): ${body.withdrawalFeed}`);
  }
  notes.push("signing times are the signers' own claims; witness with rekor-cli / ots to harden them");

  const ok = reason === null;
  return {
    ok,
    formatVersion: COUNTERSIGN_BUNDLE_FORMAT,
    requestId: typeof body.requestId === "string" ? body.requestId : null,
    requesterDid,
    requestSignatureOk: requestCheck.ok,
    requestDigestSha256: requestDigest,
    subjectPayloadType: subject.payloadType,
    subjectDigestSha256: subjectDigest,
    subjectSignatureOk,
    subjectVerifiedKeyids: verifiedKeys,
    independentSignatureCount: verifiedKeys.length,
    twoSignatureProof,
    requesterSignedSubject,
    acceptances: acceptanceReports,
    withdrawalPresented: withdrawal !== null,
    withdrawalSignatureOk,
    withdrawnBeforeSigning,
    keyClaims: keyClaimReports,
    notes,
    reason,
  };
}

/** Structural guard — true when `value` is shaped like a countersign bundle.
 *  Used by the CLI to auto-detect before the generic DSSE branch. */
export function isCountersignBundle(value: unknown): value is CountersignBundle {
  return isPlainObject(value) && value.formatVersion === COUNTERSIGN_BUNDLE_FORMAT;
}
