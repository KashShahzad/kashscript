/**
 * Countersign — the two-signature bundle and its free, offline verifier.
 *
 * ECOSYSTEM decision 26: a record signed only by the party it describes is
 * self-attestation. Decision 41 states the consequence as a rule — **two
 * signatures or it is not proof**. This module owns the *artifact* half of that
 * mechanic: the container, the four signed shapes inside it, and the one
 * function a stranger runs to check the whole thing. The *ceremony* half (the
 * request, the one-click signing path, the per-relationship key) lives in
 * `@kashscript/identity-server`, which depends on this package — never the
 * reverse.
 *
 * ── Why the verifier is here ────────────────────────────────────────────────
 * Decision 27 rule 4: verification is free and unmonopolised. attest is the
 * Apache-2.0 package a stranger installs and the home of the standalone CLI, so
 * the check lands here and nothing above it may ever gate it.
 *
 * ── The shape ───────────────────────────────────────────────────────────────
 * The countersignature is an ORDINARY DSSE signature appended to the subject
 * envelope's `signatures[]`, over `PAE(payloadType, payload)` — byte-identical
 * to what the first signer signed. Consequences worth stating:
 *
 *   • **No new envelope format, and no new DST for the thing being signed.** Any
 *     existing DSSE envelope becomes countersignable as it stands.
 *   • **Both keys resolve offline.** `did:kash` is self-certifying (ADR-0003),
 *     so `parseDidKey(keyid)` yields the public key — and its type, Ed25519 or
 *     P-256 (ADR-0020) — with no registry, no lookup and no network: decision
 *     28's "never build anything whose verification requires us", satisfied
 *     structurally rather than by policy. The algorithm comes from the key.
 *
 * A raw Ed25519 signature carries no time and no context, so the countersigner
 * makes a second signature with the SAME key: an **acceptance** Kash-Event that
 * binds the request, the subject digest, the key's custody class and the moment
 * of signing. One click, two signatures, one key.
 *
 * ── The container is trusted for nothing ────────────────────────────────────
 * `CountersignBundle` is unsigned. Every part inside it carries its own
 * signature and every binding between the parts is checked by digest, so an
 * attacker who rewrites the container can only produce a bundle that fails.
 *
 * ── Signers are keys, not spellings (AU-3, A7-02) ──────────────────────────
 * `did:kash:X` and `did:kash:X#c` resolve to one key, so they are one signer:
 * every count and every independence check here compares the canonical
 * `did:kash` of the key a keyid resolves to (`canonicalSignerOf`), and the
 * report names signers in that form. The requester's own acceptance is a
 * signature over its own claim — never a countersignature: it is reported as
 * `independent: false`, it never makes the two-signature proof, and a bundle
 * whose only verifying acceptance is the requester's own fails as
 * `COUNTERSIGNER_IS_REQUESTER`. Whether the requester signed the subject at all
 * is a fact in the report (`requesterSignedSubject`), not a rule: a cohort
 * record's requester does; an organisation requesting on its doer's record
 * does not.
 *
 * ── Never a throw (AU-3, A7-04) ─────────────────────────────────────────────
 * Anyone can append a junk sibling signature, or hand over bytes that are not
 * JSON, to a record somebody else signed. `verifyCountersignBundle` returns a
 * report for every input — `MALFORMED_BUNDLE` for what cannot be read — and
 * throws nothing: the one runtime fault, `ALG_UNAVAILABLE`, is reported as
 * `RUNTIME_CANNOT_CHECK`.
 *
 * ── Honest limits, carried in the report rather than in a footnote ──────────
 *   • `signedAtUnix` is the countersigner's own claim about when they signed.
 *     Inside the window it is consistent, not proven; a lie there is a lie under
 *     their own signature. Public-log witnessing (`./witness`) is the hardening
 *     path — this module invents nothing of its own.
 *   • Absence of a withdrawal cannot be proven offline. The report says "none
 *     presented", never "none exists". Revocation without a centre is the open
 *     problem decision 28 names; see ADR-0018 for what this does and does not
 *     answer.
 *   • A key whose custody is `delegated-mint` was generated by somebody other
 *     than its signer. Records signed under one are **not subject-held**, and
 *     the report says so on every run. Custody an acceptance does not state is
 *     `unknown` — never read as subject-held (AU-3, A7-05).
 */

